def initialize_faculty_table(db_engine: Engine = engine) -> None:
    with db_engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS faculty (
                    faculty_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(255) NOT NULL UNIQUE,
                    specialization VARCHAR(255) NOT NULL DEFAULT 'Not specified',
                    max_capacity INTEGER NOT NULL DEFAULT 2 CHECK (max_capacity >= 0)
                )
                """
            )
        )
        for faculty_name in FACULTY_SEED:
            connection.execute(
                text(
                    """
                    INSERT INTO faculty (name, specialization, max_capacity)
                    VALUES (:name, 'Not specified', 2)
                    ON CONFLICT (name) DO NOTHING
                    """
                ),
                {"name": faculty_name},
            )


def fetch_faculty(db_engine: Engine = engine) -> list[dict[str, object]]:
    with db_engine.connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT faculty_id, name, specialization, max_capacity
                FROM faculty
                ORDER BY faculty_id
                """
            )
        ).mappings()
        return [dict(row) for row in rows]
